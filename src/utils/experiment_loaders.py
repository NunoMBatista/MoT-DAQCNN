import torch
from torch.utils.data import Dataset, Subset
import numpy as np
from src.utils.data import get_medmnist_loaders
#added by Siddhanta for VIT purpose
class QuantumFeatureDataset(Dataset):
    """
    Loads the cached quantum features generated by create_quantum_dataset.py
    """
    def __init__(self, npz_path, split="train"):
        data = np.load(npz_path, allow_pickle=True)
        self.features = torch.from_numpy(data[f"{split}_features"]).float()
        self.labels = torch.from_numpy(data[f"{split}_labels"]).long()
        
    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        return self.features[idx], self.labels[idx]

def get_synced_loaders(cfg, quantum_npz_path, fraction):
    """
    Ensures both Classical and Quantum loaders use the exact same image subset.
    fraction: float between 0.1 and 1.0
    """
    seed = cfg.get("misc", {}).get("seed", 42)
    torch.manual_seed(seed)
    
    # 1. Get Classical Loaders (using your existing logic)
    cfg["dataset"]["subset_percent"] = fraction * 100
    c_train, c_val, c_test, n_classes = get_medmnist_loaders(cfg, cfg["dataset"]["name"])
    
    # 2. Get Quantum Dataset
    q_train_ds = QuantumFeatureDataset(quantum_npz_path, split="train")
    q_val_ds = QuantumFeatureDataset(quantum_npz_path, split="val")
    q_test_ds = QuantumFeatureDataset(quantum_npz_path, split="test")
    
    # 3. Apply the SAME indices to Quantum Data
    # We retrieve the indices used by the Classical Subset
    train_indices = c_train.dataset.indices 
    val_indices = c_val.dataset.indices
    
    q_train_subset = Subset(q_train_ds, train_indices)
    q_val_subset = Subset(q_val_ds, val_indices)
    
    # 4. Create Quantum Loaders
    q_train_loader = torch.utils.data.DataLoader(q_train_subset, batch_size=cfg["dataset"]["batch_size"], shuffle=True)
    q_val_loader = torch.utils.data.DataLoader(q_val_subset, batch_size=cfg["dataset"]["batch_size"], shuffle=False)
    q_test_loader = torch.utils.data.DataLoader(q_test_ds, batch_size=cfg["dataset"]["batch_size"], shuffle=False)
    
    return (c_train, c_val, c_test), (q_train_loader, q_val_loader, q_test_loader), n_classes